    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
        String noKtp = txtNoKtp.getText();

        if (noKtp.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Masukkan No. KTP terlebih dahulu!");
        } else {
            int konfirmasi = JOptionPane.showConfirmDialog(
                    this,
                    "Yakin ingin menghapus data warga ini?",
                    "Konfirmasi Hapus",
                    JOptionPane.YES_NO_OPTION
            );

            if (konfirmasi == JOptionPane.YES_OPTION) {
                perintah.hapusWarga(noKtp);
                resetForm();
            }
        }
    }//GEN-LAST:event_btnHapusActionPerformed

    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
        Warga w = new Warga();

        w.setNoKtp(txtNoKtp.getText());
        w.setIdKeluarga(txtIdKeluarga.getText());
        w.setNama(txtNama.getText());
        w.setAgama(txtAgama.getText());
        w.setTempatLahir(txtTempatLahir.getText());
        w.setTanggalLahir(txtTanggalLahir.getText());
        w.setJenisKelamin(cmbJenisKelamin.getSelectedItem().toString());
        w.setGolDarah(txtGolDarah.getText());
        w.setWargaNegara(txtWargaNegara.getText());
        w.setPendidikan(txtPendidikan.getText());
        w.setPekerjaan(txtPekerjaan.getText());
        w.setStatusNikah(txtStatusNikah.getText());
        w.setStatus(cmbStatus.getSelectedItem().toString());

        perintah.simpanWarga(w);
        resetForm();
    }//GEN-LAST:event_btnSimpanActionPerformed

    private void btnCariActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCariActionPerformed
        String noKtp = txtNoKtp.getText();

        if (noKtp.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Masukkan No. KTP terlebih dahulu!");
        } else {
            Warga w = perintah.cariWarga(noKtp);

            if (w != null) {
                txtNoKtp.setText(w.getNoKtp());
                txtIdKeluarga.setText(w.getIdKeluarga());
                txtNama.setText(w.getNama());
                txtAgama.setText(w.getAgama());
                txtTempatLahir.setText(w.getTempatLahir());
                txtTanggalLahir.setText(w.getTanggalLahir());
                cmbJenisKelamin.setSelectedItem(w.getJenisKelamin());
                txtGolDarah.setText(w.getGolDarah());
                txtWargaNegara.setText(w.getWargaNegara());
                txtPendidikan.setText(w.getPendidikan());
                txtPekerjaan.setText(w.getPekerjaan());
                txtStatusNikah.setText(w.getStatusNikah());
                cmbStatus.setSelectedItem(w.getStatus());
            } else {
                JOptionPane.showMessageDialog(this,
                        "Data warga tidak ditemukan!");
            }
        }
    }//GEN-LAST:event_btnCariActionPerformed

